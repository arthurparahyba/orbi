// Replaces the server entry Flue generates (dist/server.mjs) with Orbi's: the
// same start and graceful shutdown, but listening only on this machine.
// Flue's entry passes no hostname, so Node would listen on every network
// interface, and anyone on the same Wi-Fi could reach the API and the agent.
// Runs after `vite build` (see package.json). ORBI_HOST overrides, e.g. for a
// container that must be reached from outside.
import { existsSync, writeFileSync } from 'node:fs';

const dist = new URL('../dist/', import.meta.url);
if (!existsSync(new URL('app.mjs', dist))) throw new Error('dist/app.mjs não existe: rode vite build antes');

writeFileSync(
  new URL('server.mjs', dist),
  `// Generated by scripts/write-entry.mjs: Flue's Node entry, bound to 127.0.0.1.
import { startFlueNodeServer } from './app.mjs';

const lifecycle = await startFlueNodeServer({
  port: Number.parseInt(process.env.PORT || '3000', 10),
  hostname: process.env.ORBI_HOST || '127.0.0.1',
});

async function stop(exitCode) {
  setTimeout(() => {
    console.error('[orbi] encerramento demorou demais; saindo.');
    process.exit(exitCode);
  }, 60_000).unref();
  await lifecycle.stop();
  process.exit(exitCode);
}
process.on('SIGINT', () => void stop(130));
process.on('SIGTERM', () => void stop(143));
process.on('disconnect', () => void stop(0));
`,
);
console.log('dist/server.mjs: escutando só em 127.0.0.1 (ORBI_HOST muda)');
